  String get verifyNumber;

  /// No description provided for @sentCode.
  ///
  /// In en, this message translates to:
  /// **'We sent a 4-digit code to your phone'**
  String get sentCode;

  /// No description provided for @resendCode.
  ///
  /// In en, this message translates to:
  /// **'Resend Code'**
  String get resendCode;

  /// No description provided for @verifyLogin.
  ///
  /// In en, this message translates to:
  /// **'Verify & Login'**
  String get verifyLogin;

  /// No description provided for @safeTrusted.
  ///
